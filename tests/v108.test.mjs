const MUT = [
  ["src", "ρωτάς «Πόσες παραλαβές κάνεις τη μέρα;» — ποτέ «πόσα τιμολόγια ανά παραλαβή»", "ρωτάς πόσα τιμολόγια περνάει σε κάθε παραλαβή"], // 1 · 🔴 λάθος ερώτηση
  ["know", "από αυτό ΤΡΙΑ ποσά: καθαρό, ΦΠΑ, τελικό", "από αυτό ένα ποσό"],                                                                         // 2 · λάθος εικόνα του Free
  ["know", "Δεν ξαναπληκτρολογεί τίποτα — άρα κανένα λάθος πληκτρολόγησης. (Μη λες «κανένα λάθος» απόλυτα", "Κανένα λάθος δεν γίνεται ποτέ. ("],      // 3 · 🔴 απόλυτος ισχυρισμός ακρίβειας
  ["know", "Η ΜΕΓΑΛΗ αξία του πληρωμένου κλειδιού έρχεται με το PRO (σχεδιάζεται — καμία ημερομηνία, καμία τιμή)", "Το PRO έρχεται τον Νοέμβριο"],   // 4 · 🔴 ημερομηνία PRO
  ["know", "η τελευταία τιμή κόστους, πόσα αγόρασε συνολικά, και η μέση τιμή του", "η τιμή"],                                                        // 5 · λείπει ο «μαγικός αριθμός»
];
if (ONLY) { const m = MUT[ONLY - 1]; if (!m) process.exit(2); const bag = { src, know };
  if (!bag[m[0]].includes(m[1])) { console.log("Μ" + ONLY + " ΔΕΝ ΒΡΗΚΕ ΣΤΟΧΟ"); process.exit(3); }
  bag[m[0]] = bag[m[0]].replace(m[1], m[2]); ({ src, know } = bag); }
let failed = 0;
const check = (n, f) => { try { f(); if (!ONLY) console.log("  ✔ " + n); } catch (e) { failed++; console.log("  ✘ " + n + " — " + e.message); } };
const ok = (c, m) => { if (!c) throw new Error(m); };
check("Ν108-1 · 🔴 κανόνας: ένα τιμολόγιο ανά παραλαβή, «Πόσες παραλαβές κάνεις τη μέρα;»", () => {
  ok(src.includes("Σε κάθε παραλαβή περνάει ΕΝΑ τιμολόγιο με τρία ποσά (καθαρό, ΦΠΑ, τελικό)"), "τρία ποσά");
  ok(src.includes("ρωτάς «Πόσες παραλαβές κάνεις τη μέρα;» — ποτέ «πόσα τιμολόγια ανά παραλαβή»"), "ερώτηση");
});
check("Ν108-2 · γνώση: Free = ένα τιμολόγιο, τρία ποσά · κλειδί = φωτογραφία + επιβεβαίωση · χωρίς απόλυτο «κανένα λάθος»", () => {
  ok(know.includes("σε κάθε παραλαβή περνάει ΕΝΑ τιμολόγιο, και από αυτό ΤΡΙΑ ποσά: καθαρό, ΦΠΑ, τελικό"), "Free");
  ok(know.includes("Η ΣΩΣΤΗ ερώτηση είναι «Πόσες παραλαβές κάνεις τη μέρα;»"), "ερώτηση");
  ok(know.includes("Δεν ξαναπληκτρολογεί τίποτα — άρα κανένα λάθος πληκτρολόγησης. (Μη λες «κανένα λάθος» απόλυτα"), "λάθη");
  ok(!/Κανένα λάθος δεν γίνεται|ΚΑΝΕΝΑ λάθος ΔΕΝ προκαλείται/.test(know), "απόλυτος ισχυρισμός");
});
check("Ν108-3 · 🔴 PRO: όλα τα προϊόντα με μία φωτογραφία + «μαγικός αριθμός» ανά κωδικό — ΧΩΡΙΣ ημερομηνία/τιμή", () => {
  ok(know.includes("Η ΜΕΓΑΛΗ αξία του πληρωμένου κλειδιού έρχεται με το PRO (σχεδιάζεται — καμία ημερομηνία, καμία τιμή)"), "PRO");
  ok(know.includes("με μία φωτογραφία θα καταγράφονται ταυτόχρονα ΟΛΑ τα προϊόντα του τιμολογίου"), "όλα τα προϊόντα");
  ok(know.includes("η τελευταία τιμή κόστους, πόσα αγόρασε συνολικά, και η μέση τιμή του"), "μαγικός αριθμός");
  ok(!/PRO[^.\n]{0,60}(Ιανουάρ|Φεβρουάρ|Μάρτ|Απρίλ|Μάι|Ιούν|Ιούλ|Αύγουστ|Σεπτέμβρ|Οκτώβρ|Νοέμβρ|Δεκέμβρ|20\d\d)/.test(know.replace("Από 12/10/2026 με προπληρωμή", "")), "ημερομηνία PRO");
});
if (ONLY) { if (failed) { console.log("Μ" + ONLY + " → κοκκίνισε ✔"); process.exit(0); } console.log("Μ" + ONLY + " ΠΕΡΑΣΕ — το τεστ δεν πιάνει τίποτα"); process.exit(1); }
console.log(failed ? "ΑΠΕΤΥΧΑΝ " + failed : "✔ ΟΛΑ ΠΕΡΑΣΑΝ (3)"); process.exit(failed ? 1 : 0);
