// v109 · «Πληρωμένο» κλειδί ≈ κάτω από 1 € τον μήνα (Stavros 1/10/2026) — υπολογισμός με τις παραλαβές της μέρας ·
//        η ώρα της παραλαβής (πρωί/απόγευμα) ΔΕΝ είναι ποτέ επιχείρημα.
//   node tests/v109.test.mjs  ·  --mutate=N (ΠΡΕΠΕΙ να κοκκινίσει)
import { readFileSync } from "node:fs";
const ONLY = (() => { const a = process.argv.find((x) => x.startsWith("--mutate=")); return a ? Number(a.split("=")[1]) : null; })();
let src = readFileSync("src/km.js", "utf8");
let know = readFileSync("site/kostometro/agent/knowledge_el.md", "utf8");
const MUT = [
  ["know", "για τις περισσότερες επιχειρήσεις κάτω από 1 € τον μήνα. (v109", "για τις περισσότερες επιχειρήσεις ακριβό. (v109"],                    // 1 · λείπει το «κάτω από 1 €»
  ["know", "παραλαβές τη μέρα × ~26 εργάσιμες × 0,005 €", "κάτι"],                                                                                 // 2 · χωρίς υπολογισμό
  ["know", "Λες πάντα ότι είναι ενδεικτικό και ότι την τιμή την ορίζει η Google.", "Η τιμή είναι εγγυημένη."],                                      // 3 · 🔴 δέσμευση σε τιμή τρίτου
  ["know", "  - Πληρωμένο κλειδί: σταθερή ανάγνωση σε κάθε παραλαβή.", "  - Πληρωμένο κλειδί: σταθερή ανάγνωση, και στις πρωινές παραλαβές."],     // 4 · 🔴 ξανά «πρωινές»
  ["src", "Η ώρα της παραλαβής (πρωί/απόγευμα) ΔΕΝ είναι ποτέ επιχείρημα.", ""],                                                                   // 5 · κανόνας ώρας
];
if (ONLY) { const m = MUT[ONLY - 1]; if (!m) process.exit(2); const bag = { src, know };
  if (!bag[m[0]].includes(m[1])) { console.log("Μ" + ONLY + " ΔΕΝ ΒΡΗΚΕ ΣΤΟΧΟ"); process.exit(3); }
  bag[m[0]] = bag[m[0]].replace(m[1], m[2]); ({ src, know } = bag); }
let failed = 0;
const check = (n, f) => { try { f(); if (!ONLY) console.log("  ✔ " + n); } catch (e) { failed++; console.log("  ✘ " + n + " — " + e.message); } };
const ok = (c, m) => { if (!c) throw new Error(m); };
check("Ν109-1 · κόστος πληρωμένου: ≈0,50 €/100 τιμολόγια, κάτω από 1 € τον μήνα, υπολογισμός με τις παραλαβές, «ενδεικτικό — την ορίζει η Google»", () => {
  ok(know.includes("για τις περισσότερες επιχειρήσεις κάτω από 1 € τον μήνα. (v109"), "κάτω από 1 €");
  ok(know.includes("περίπου 0,50 € ανά 100 τιμολόγια (τιμή της Google, που μπορεί να αλλάξει)"), "0,50/100 (ίδιο με το FAQ)");
  ok(know.includes("παραλαβές τη μέρα × ~26 εργάσιμες × 0,005 €") && know.includes("5 τη μέρα ≈ 130 τιμολόγια ≈ 0,65 € τον μήνα"), "υπολογισμός");
  ok(Math.abs(5 * 26 * 0.005 - 0.65) < 1e-9, "αριθμητική του παραδείγματος");
  ok(know.includes("Λες πάντα ότι είναι ενδεικτικό και ότι την τιμή την ορίζει η Google."), "ενδεικτικό");
  ok(know.includes("ενδεικτικά περίπου 0,50 € για 100 τιμολόγια"), "το FAQ λέει το ίδιο νούμερο");
});
check("Ν109-2 · 🔴 η ώρα δεν είναι επιχείρημα: καμία «πρωινή παραλαβή» στη γνώση/κανόνες, ρητή απαγόρευση", () => {
  const strip = (t) => t.replace(/ΜΗ λες «πρωινές παραλαβές», «νωρίς το πρωί», «μόλις ξύπνησε»/g, "").replace(/πρωί ή απόγευμα|πρωί\/απόγευμα/g, "");
  ok(!/πρωιν|το πρωί/i.test(strip(know)), "γνώση: " + (strip(know).match(/.{30}(πρωιν|το πρωί).{30}/i) || [])[0]);
  ok(!/πρωιν/i.test(strip(src)), "κώδικας");
  ok(know.includes("🔴 Η ώρα της παραλαβής ΔΕΝ είναι επιχείρημα") && src.includes("Η ώρα της παραλαβής (πρωί/απόγευμα) ΔΕΝ είναι ποτέ επιχείρημα."), "απαγόρευση");
});
if (ONLY) { if (failed) { console.log("Μ" + ONLY + " → κοκκίνισε ✔"); process.exit(0); } console.log("Μ" + ONLY + " ΠΕΡΑΣΕ — το τεστ δεν πιάνει τίποτα"); process.exit(1); }
console.log(failed ? "ΑΠΕΤΥΧΑΝ " + failed : "✔ ΟΛΑ ΠΕΡΑΣΑΝ (2)"); process.exit(failed ? 1 : 0);
