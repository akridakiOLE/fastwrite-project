-- (Brief Η.11β, 15/9/2026 · ξανάνοιξε το κλειστό θέμα Η.11 της 9/9 με εντολή Stavros)
--
-- Τρέχει ΜΙΑ φορά, ΜΕΤΑ το km_mail.sql:
--   npx wrangler d1 execute fastwrite-beta-downloads --remote --file=schema/km_h11b.sql
-- Τοπικά (δοκιμές):
--   npx wrangler d1 execute fastwrite-beta-downloads --local  --file=schema/km_h11b.sql
--
-- Κανόνας Α400 §Γ: ποτέ DROP, μόνο ADD.
-- ⚠ Δεύτερη εκτέλεση βγάζει «duplicate column» — ΕΧΕΙ ΗΔΗ ΤΡΕΞΕΙ, δεν είναι σφάλμα.
--
-- ΓΙΑΤΙ:
--   Ως τις 15/9 η διαγραφή ήταν ακαριαία και αμετάκλητη. Οι τρεις φρουροί της
--   (ενεργή συσκευή · κλείδωμα συσκευής · η λέξη ΔΙΑΓΡΑΦΗ) τους περνάει ΟΛΟΥΣ
--   όποιος κρατάει το ξεκλείδωτο κινητό. Το email ειδοποίησης έφτανε ΜΕΤΑ, όταν
--   δεν υπήρχε τίποτα να σωθεί — εύρημα Stavros 15/9 μετά την πρώτη πραγματική
--   δοκιμή αποστολής από tablet.
--
--   Τώρα η διαγραφή είναι ΑΙΤΗΜΑ που ωριμάζει σε 72 ώρες. Στο ενδιάμεσο ο
--   λογαριασμός ΠΑΓΩΝΕΙ (423) — ο κλέφτης δεν κερδίζει χρόνο πρόσβασης, τον
--   χάνει. Η ακύρωση γίνεται ΜΕ ΤΙΣ 12 ΛΕΞΕΙΣ, ποτέ με σύνδεσμο: ο σύνδεσμος
--   ζει στο email, και το email ζει μέσα στο ίδιο κλεμμένο κινητό.
--
-- ΔΥΟ ΣΤΗΛΕΣ, ΚΑΙ ΟΙ ΔΥΟ ΓΡΑΦΟΝΤΑΙ ΡΗΤΑ:
--   Το delete_due_at ΔΕΝ υπολογίζεται κατά την ανάγνωση. Αν υπολογιζόταν, μια
--   μελλοντική αλλαγή του ορίου (72 → 48) θα μετακινούσε αναδρομικά τη λήξη
--   λογαριασμών που είχαν ήδη ειδοποιηθεί με άλλη ώρα — και το email θα είχε
--   πει ψέματα. Ο,τι υποσχέθηκε το email, το κρατάει η βάση.

ALTER TABLE km_accounts ADD COLUMN delete_requested_at TEXT;
ALTER TABLE km_accounts ADD COLUMN delete_due_at TEXT;

-- Το cron σαρώνει «ποιοι έληξαν» κάθε ώρα. Χωρίς δείκτη είναι πλήρης σάρωση
-- του μητρώου 24 φορές την ημέρα, για πάντα.
CREATE INDEX IF NOT EXISTS idx_km_accounts_delete_due ON km_accounts (delete_due_at);
