-- ΤΙ ΔΕΝ ΥΠΑΡΧΕΙ ΕΔΩ, ΚΑΙ ΕΙΝΑΙ ΣΚΟΠΙΜΟ:
--   • κανένα folder_id  • κανένα install_id  • καμία IP  • καμία ώρα
-- Η γνώμη ΔΕΝ συνδέεται με λογαριασμό. Ο μήνας (όχι η ημέρα) είναι ό,τι
-- χρειάζεται για να ξέρουμε πότε ειπώθηκε. Email υπάρχει ΜΟΝΟ αν ο ίδιος
-- τσεκάρισε «Θέλω απάντηση».
-- ═══════════════════════════════════════════════════════════════════════════

CREATE TABLE IF NOT EXISTS km_feedback (
  id      INTEGER PRIMARY KEY AUTOINCREMENT,
  stars   INTEGER,              -- 1-5, ή NULL αν δεν βαθμολόγησε
  text    TEXT,                 -- έως 2.000 χαρακτήρες
  ver     TEXT,                 -- έκδοση εφαρμογής, π.χ. "v60"
  month   TEXT NOT NULL,        -- "2026-09" — μήνας, ΟΧΙ ημέρα, ΟΧΙ ώρα
  country TEXT,                 -- από τη Cloudflare (request.cf.country)
  email   TEXT                  -- ΜΟΝΟ αν ζήτησε απάντηση, αλλιώς NULL
);

CREATE INDEX IF NOT EXISTS idx_km_feedback_month ON km_feedback(month);

-- ───────────────────────────────────────────────────────────────────────────
-- ΦΡΕΝΟ ΚΑΤΑΧΡΗΣΗΣ — έως 5 μηνύματα ανά συσκευή ανά ημέρα (Brief Ε §3).
--
-- Το κλειδί είναι sha256(install_id + ":" + ΗΗΗΗ-ΜΜ-ΗΗ). Αλλάζει κάθε μέρα,
-- άρα ΔΕΝ συνδέει τη μια μέρα με την άλλη: δεν μπορεί να χτιστεί ιστορικό
-- συσκευής από αυτόν τον πίνακα. Το install_id ΔΕΝ αποθηκεύεται πουθενά.
--
-- Ο πίνακας κρατάει το ελάχιστο και καθαρίζεται μόνος του: κάθε γραφή σβήνει
-- ό,τι είναι παλαιότερο από δύο ημέρες.
-- ───────────────────────────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS km_feedback_rate (
  day_hash TEXT PRIMARY KEY,    -- sha256(install_id + ":" + ημερομηνία)
  day      TEXT NOT NULL,       -- "2026-09-14" — μόνο για τον καθαρισμό
  n        INTEGER NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_km_feedback_rate_day ON km_feedback_rate(day);
