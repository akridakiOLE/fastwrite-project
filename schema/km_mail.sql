-- km_mail_log — ημερολόγιο ειδοποιήσεων (Brief Ε §6). Γράφτηκε 14/9/2026.
--
-- 🔴 ΓΙΑΤΙ ΥΠΑΡΧΕΙ: ο κανόνας του Brief Ε λέει «ειδοποίηση, όχι επιβεβαίωση» —
--    αν το email αποτύχει, η πράξη ΔΕΝ ακυρώνεται. Αλλά μια αποτυχία που δεν
--    τη βλέπει κανείς είναι σαν να μην έγινε ποτέ. Εδώ φαίνεται.
--
-- 🔴 ΤΙ ΔΕΝ ΓΡΑΦΕΤΑΙ ΕΔΩ, ΚΑΙ ΕΙΝΑΙ ΤΟ ΣΗΜΑΝΤΙΚΟΤΕΡΟ:
--    ΚΑΜΙΑ διεύθυνση παραλήπτη. Η ειδοποίηση διαγραφής φεύγει τη στιγμή που
--    σβήνεται ο λογαριασμός· αν κρατούσαμε το email εδώ, θα ανασταίναμε
--    ακριβώς αυτό που μόλις διαγράψαμε. Κρατάμε ΜΟΝΟ: τι είδους ειδοποίηση,
--    αν πέτυχε, το σφάλμα αν απέτυχε, και το messageId της Cloudflare.
-- ═══════════════════════════════════════════════════════════════════════════

CREATE TABLE IF NOT EXISTS km_mail_log (
  id     INTEGER PRIMARY KEY AUTOINCREMENT,
  kind   TEXT NOT NULL,   -- 'deleted' | 'words'
  ok     INTEGER NOT NULL DEFAULT 0,
  err    TEXT,            -- το μήνυμα σφάλματος, αν απέτυχε
  msg_id TEXT,            -- messageId της Cloudflare, αν πέτυχε
  at     TEXT NOT NULL    -- ISO-8601 UTC. Ώρα χρειάζεται: χωρίς αυτήν δεν
                          -- διαγιγνώσκεται τίποτα. Δεν συνδέεται με πρόσωπο.
);

CREATE INDEX IF NOT EXISTS idx_km_mail_log_at ON km_mail_log(at);
CREATE INDEX IF NOT EXISTS idx_km_mail_log_ok ON km_mail_log(ok);
