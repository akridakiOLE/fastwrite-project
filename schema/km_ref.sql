--   site/kostometro/app.js:1781  refCode() = localStorage('km_install_id').slice(-8)
--   site/kostometro/app.js:3932  το install_id γεννιέται ΣΤΗ ΣΥΣΚΕΥΗ, τυχαία.
-- Συνέπειες που μετρήθηκαν, όχι εικασίες:
--   (α) αλλαγή κινητού / επανεγκατάσταση / καθαρισμός δεδομένων => ΝΕΟΣ κωδικός.
--       Οι συστάσεις που είχαν ήδη γραφτεί στο km_accounts.ref με τον ΠΑΛΙΟ
--       κωδικό μένουν ορφανές: ο χρήστης τις χάνει χωρίς να φταίει.
--   (β) ίδιος χρήστης σε δύο συσκευές => δύο κωδικοί, οι συστάσεις σπάνε στα δύο.
--   (γ) 8 χαρακτήρες από timestamp+random, ΧΩΡΙΣ έλεγχο μοναδικότητας στον
--       server: δύο χρήστες μπορούν να πάρουν τον ίδιο κωδικό και η σύσταση να
--       πιστωθεί σε λάθος άτομο.
-- Η οθόνη «Κάλεσε» υπόσχεται «ένας σύνδεσμος ανά λογαριασμό, μία φορά».
-- Από σήμερα ο κωδικός βγαίνει από το folder_id (τις 12 λέξεις) και επιβιώνει
-- τα πάντα, όπως ο ίδιος ο λογαριασμός.
--
-- ΠΟΤΕ DROP. Μόνο προσθήκη. Τρέχει πολλές φορές χωρίς ζημιά.

ALTER TABLE km_accounts ADD COLUMN ref_code TEXT;
CREATE UNIQUE INDEX IF NOT EXISTS idx_km_accounts_refcode ON km_accounts (ref_code);

-- ΑΝΟΙΓΜΑΤΑ ΤΟΥ ΣΥΝΔΕΣΜΟΥ.
-- ⚠ Μετράει ΑΝΟΙΓΜΑΤΑ, ΟΧΙ «προσκλήσεις που έστειλες»: το Web Share API δεν
-- επιστρέφει ποτέ αν ο χρήστης όντως έστειλε, σε ποιον, ή αν ακύρωσε. Μετρητής
-- «έστειλες» θα μετρούσε πατήματα κουμπιού — νούμερο που λέει ψέματα από τον
-- πρώτο μήνα, πάνω σε οθόνη που υπόσχεται «δεν χάνονται».
-- Το (ref_code, install_id) ως πρωτεύον κλειδί κάνει το de-duplication μόνο του:
-- η ίδια συσκευή μετριέται ΜΙΑ φορά όσες φορές κι αν ανοίξει τον σύνδεσμο.
CREATE TABLE IF NOT EXISTS km_ref_hits (
  ref_code   TEXT NOT NULL,
  install_id TEXT NOT NULL,
  first_seen TEXT NOT NULL,
  country    TEXT,
  PRIMARY KEY (ref_code, install_id)
);
CREATE INDEX IF NOT EXISTS idx_km_ref_hits_code ON km_ref_hits (ref_code);
